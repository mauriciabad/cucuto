// Latest stable NDK (r30). Needed by cargo-ndk to target API 37.
val ndkVersionPinned = "30.0.16248370"
val spikeDir: File = rootDir.parentFile // spikes/jxl

android {
    namespace = "app.mauri.cucuto.jxl"
    compileSdk = 37
    ndkVersion = ndkVersionPinned

    defaultConfig {
        applicationId = "app.mauri.cucuto.jxlspike"
        minSdk = 37
        targetSdk = 37
        versionCode = 1
        versionName = "0.1-jxl-spike"
        ndk { abiFilters += "arm64-v8a" }
    }

    buildTypes {
        // Benchmark the release build: jxl-coder publishes separate debug and release AARs and a
        // debug app would pick its unoptimised debug natives. Debug-signed, local use only.
        release {
            isMinifyEnabled = false
            signingConfig = signingConfigs.getByName("debug")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_21
        targetCompatibility = JavaVersion.VERSION_21
    }
}

/** Builds `spikes/jxl/rust` for arm64-v8a with cargo-ndk into a generated jniLibs directory. */
abstract class CargoNdkTask : DefaultTask() {
    @get:Inject abstract val exec: ExecOperations
    @get:Internal abstract val crateDir: DirectoryProperty
    @get:Input abstract val ndkHome: Property<String>
    @get:OutputDirectory abstract val outputDir: DirectoryProperty

    @TaskAction
    fun build() {
        // rustup (Homebrew) and `cargo install cargo-ndk` locations, ahead of the daemon's PATH.
        val path = listOf("${System.getProperty("user.home")}/.cargo/bin", "/opt/homebrew/opt/rustup/bin") +
            System.getenv("PATH").split(File.pathSeparator)
        val cargo = path.map { File(it, "cargo") }.firstOrNull { it.canExecute() }?.path ?: "cargo"
        exec.exec {
            workingDir = crateDir.get().asFile
            environment("ANDROID_NDK_HOME", ndkHome.get())
            environment("PATH", path.joinToString(File.pathSeparator))
            commandLine(
                cargo, "ndk", "-t", "arm64-v8a", "-P", "37",
                "-o", outputDir.get().asFile.path,
                "build", "--release", "--lib",
            )
        }
    }
}

val cargoNdk = tasks.register<CargoNdkTask>("cargoNdk") {
    crateDir.set(File(spikeDir, "rust"))
    inputs.files(fileTree(File(spikeDir, "rust/src")), File(spikeDir, "rust/Cargo.toml"))
    ndkHome.set(androidComponents.sdkComponents.sdkDirectory.map { it.dir("ndk/$ndkVersionPinned").asFile.path })
}

androidComponents {
    onVariants { variant ->
        variant.sources.jniLibs?.addGeneratedSourceDirectory(cargoNdk, CargoNdkTask::outputDir)
        // Test images are generated by ../make-test-images.main.kts, never committed.
        variant.sources.assets?.addStaticSourceDirectory(File(spikeDir, "build/test-images").path)
    }
}

