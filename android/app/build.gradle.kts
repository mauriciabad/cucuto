// Where `exportWebScreenshots` writes the website's screenshots, and whether this build runs it.
val webScreenshots: Directory = layout.projectDirectory.dir("../../web/src/lib/assets/images/screenshots")
val exportWebScreenshots = gradle.startParameter.taskNames.any { it.substringAfterLast(':') == "exportWebScreenshots" }

// Where `exportStoreScreenshots` writes the store listing's screenshots (fastlane layout, ADR 0046).
val storeScreenshots: Directory = layout.projectDirectory.dir("../../fastlane/metadata/android")
val exportStoreScreenshots =
    gradle.startParameter.taskNames.any { it.substringAfterLast(':') == "exportStoreScreenshots" }

android {
    namespace = "app.mauri.cucuto"

    defaultConfig {
        applicationId = "app.mauri.cucuto"
        // Defaults for local and CI builds. Releases take both from the tag (`-Pcucuto.version`, release.yml):
        // versionCode = MAJOR * 1_000_000 + MINOR * 1_000 + PATCH (ADR 0021, docs/releasing.md).
        versionCode = 1
        versionName = "0.1.0"
    }

    androidResources {
        // Per-app language (Android 13+ system settings, ADR 0036): AGP writes the LocaleConfig and the manifest's
        // android:localeConfig from the values-* folders; res/resources.properties names the default (English).
        generateLocaleConfig = true
        // Ship only the app's languages, so library strings never mix a third language into the UI.
        localeFilters += listOf("en", "es")
    }

    bundle {
        // The Play bundle keeps both languages in the base APK (ADR 0071): the language is picked per app (ADR 0036),
        // and Play clients that only fetch the phone language's split would leave the other one without strings.
        language {
            enableSplit = false
        }
    }

    buildFeatures {
        // BuildConfig.DEBUG gates the design gallery.
        buildConfig = true
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
        }
    }

    testOptions {
        // Robolectric needs the merged resources (strings) for the Compose UI tests.
        unitTests.isIncludeAndroidResources = true
        unitTests.all {
            // Robolectric's Android 16+ runtime touches FileDescriptor internals that JDK 21 hides by default.
            it.jvmArgs("--add-opens=java.base/jdk.internal.access=ALL-UNNAMED")
            // The screenshot tests draw the demo packs' sprites and covers straight from packs/ (ADR 0032).
            it.inputs
                .dir("../../packs")
                .withPropertyName("demoPacks")
                .withPathSensitivity(PathSensitivity.RELATIVE)
            if (exportWebScreenshots) {
                it.systemProperty("cucuto.screenshots.web", webScreenshots.asFile.absolutePath)
                it.outputs.dir(webScreenshots)
                it.outputs.upToDateWhen { false }
            }
            if (exportStoreScreenshots) {
                it.systemProperty("cucuto.screenshots.store", storeScreenshots.asFile.absolutePath)
                it.outputs.upToDateWhen { false }
            }
        }
    }

    sourceSets {
        named("main") {
            // Brand tokens and the adaptive icon are compiled straight from brand/ (single source of truth,
            // regenerated by brand/tools). See docs/decisions/0003-brand-assets-by-reference.md.
            kotlin.directories += "../../brand/tokens"
            res.directories += "../../brand/app-icon/android-res"
        }
    }
}

// Website screenshots (ADR 0032): records the screenshot tests and also writes the images of the tests that name a
// `web` image to the website, which encodes them to JPEG XL, AVIF and PNG at build time.
tasks.register("exportWebScreenshots") {
    group = "verification"
    description = "Records the screenshot tests and writes the website's screenshots to web/src/lib/assets/images/."
    dependsOn("recordRoborazziDebug")
}

// Store listing screenshots (ADR 0046): the same, for the tests with a `store` position, into fastlane's
// metadata/android/<locale>/images/phoneScreenshots/, which F-Droid, IzzyOnDroid and Obtainium read.
tasks.register("exportStoreScreenshots") {
    group = "verification"
    description = "Records the screenshot tests and writes the store listing's screenshots to fastlane/metadata/."
    dependsOn("recordRoborazziDebug")
}

// Brand UI sounds (brand/sounds/*.ogg) become R.raw.ui_* through a generated resource directory.
val brandSounds =
    tasks.register<BrandSoundsTask>("brandSounds") {
        sounds.from(fileTree("../../brand/sounds") { include("*.ogg") })
    }

androidComponents {
    onVariants { variant ->
        variant.sources.res?.addGeneratedSourceDirectory(brandSounds, BrandSoundsTask::outputDirectory)
    }
}

