// Generates the cucuto color tokens with the official Material Color Utilities.
//   cd brand/tools && pnpm install && pnpm tokens
// Outputs brand/tokens/colors.json, Color.kt and colors.css. Never edit those by hand: change this file and rerun.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { mcu } from './mcu.mjs';

const { Hct, SchemeVibrant, MaterialDynamicColors, hexFromArgb, argbFromHex } = mcu;

/** The brand seed: "cuckoo tangerine". */
const SEED = '#FF6B2C';
/** Scheme variant used for the fallback themes (when dynamic color is off) and for character accents. */
const VARIANT = SchemeVibrant;
const VARIANT_NAME = 'vibrant';
const SPEC = '2025';
const PLATFORM = 'phone';

/** Example character accent seeds, the way the app derives a scheme from a sprite's dominant color. */
const CHARACTER_SEEDS = {
  leaf: '#3FAE5A',
  sky: '#3D8BFF',
  berry: '#D9468F',
  plum: '#8E5CFF',
  sunny: '#FFC233',
  slate: '#5F7A8A',
};

const CONTRASTS = { standard: 0, medium: 0.5, high: 1 };

const TONES = [0, 4, 5, 6, 10, 12, 15, 17, 20, 22, 24, 25, 30, 35, 40, 50, 60, 70, 80, 87, 90, 92, 94, 95, 96, 98, 99, 100];

// Compose ColorScheme parameter order (androidx.compose.material3 1.4+/1.5).
const ROLES = [
  'primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer', 'inversePrimary',
  'secondary', 'onSecondary', 'secondaryContainer', 'onSecondaryContainer',
  'tertiary', 'onTertiary', 'tertiaryContainer', 'onTertiaryContainer',
  'background', 'onBackground', 'surface', 'onSurface', 'surfaceVariant', 'onSurfaceVariant',
  'surfaceTint', 'inverseSurface', 'inverseOnSurface',
  'error', 'onError', 'errorContainer', 'onErrorContainer',
  'outline', 'outlineVariant', 'scrim',
  'surfaceBright', 'surfaceContainer', 'surfaceContainerHigh', 'surfaceContainerHighest',
  'surfaceContainerLow', 'surfaceContainerLowest', 'surfaceDim',
  'primaryFixed', 'primaryFixedDim', 'onPrimaryFixed', 'onPrimaryFixedVariant',
  'secondaryFixed', 'secondaryFixedDim', 'onSecondaryFixed', 'onSecondaryFixedVariant',
  'tertiaryFixed', 'tertiaryFixedDim', 'onTertiaryFixed', 'onTertiaryFixedVariant',
];

const scheme = (seed, dark, contrast = 0) => new VARIANT(Hct.fromInt(argbFromHex(seed)), dark, contrast, SPEC, PLATFORM);
const roleHex = (s, role) => hexFromArgb(MaterialDynamicColors[role].getArgb(s)).toUpperCase();
const roles = (s) => Object.fromEntries(ROLES.map((r) => [r, roleHex(s, r)]));
const palette = (p) => Object.fromEntries(TONES.map((t) => [t, hexFromArgb(p.tone(t)).toUpperCase()]));
const kebab = (s) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const pascal = (s) => s[0].toUpperCase() + s.slice(1);

const light = scheme(SEED, false);
const palettes = {
  primary: palette(light.primaryPalette),
  secondary: palette(light.secondaryPalette),
  tertiary: palette(light.tertiaryPalette),
  neutral: palette(light.neutralPalette),
  neutralVariant: palette(light.neutralVariantPalette),
  error: palette(light.errorPalette),
};

const schemes = {};
for (const [cName, c] of Object.entries(CONTRASTS)) {
  for (const dark of [false, true]) {
    schemes[`${dark ? 'dark' : 'light'}${cName === 'standard' ? '' : `${pascal(cName)}Contrast`}`] = roles(scheme(SEED, dark, c));
  }
}

const characters = Object.fromEntries(Object.entries(CHARACTER_SEEDS).map(([name, seed]) => {
  const pick = (dark) => {
    const s = scheme(seed, dark);
    return Object.fromEntries(['primary', 'onPrimary', 'primaryContainer', 'onPrimaryContainer', 'surfaceContainer']
      .map((r) => [r, roleHex(s, r)]));
  };
  return [name, { seed, light: pick(false), dark: pick(true) }];
}));

const outDir = fileURLToPath(new URL('../tokens/', import.meta.url));
const generatedNote = `Generated by brand/tools/generate-tokens.mjs with @material/material-color-utilities 0.4.0 (Scheme${pascal(VARIANT_NAME)}, spec ${SPEC}). Do not edit by hand.`;

// colors.json: W3C Design Tokens Community Group format.
const tok = (hex) => ({ $type: 'color', $value: hex });
const mapTokens = (obj) => Object.fromEntries(Object.entries(obj).map(([k, v]) => [k, tok(v)]));
const json = {
  $description: generatedNote,
  seed: { ...tok(SEED), $description: 'cucuto brand seed, "cuckoo tangerine"' },
  meta: { $type: 'string', variant: { $value: VARIANT_NAME }, specVersion: { $value: SPEC }, platform: { $value: PLATFORM } },
  palette: Object.fromEntries(Object.entries(palettes).map(([k, v]) => [k, mapTokens(v)])),
  scheme: Object.fromEntries(Object.entries(schemes).map(([k, v]) => [k, mapTokens(v)])),
  character: Object.fromEntries(Object.entries(characters).map(([k, v]) => [k, {
    seed: tok(v.seed), light: mapTokens(v.light), dark: mapTokens(v.dark),
  }])),
};
writeFileSync(`${outDir}colors.json`, `${JSON.stringify(json, null, 2)}\n`);

// Color.kt: Compose fallbacks for when dynamic color is off.
const kHex = (hex) => `Color(0xFF${hex.slice(1)})`;
let kt = `// ${generatedNote}\npackage app.mauri.cucuto.ui.theme\n\nimport androidx.compose.material3.ColorScheme\nimport androidx.compose.material3.darkColorScheme\nimport androidx.compose.material3.lightColorScheme\nimport androidx.compose.ui.graphics.Color\n\n`;
kt += `/** cucuto brand seed, "cuckoo tangerine". Feed it to a dynamic scheme when a seed is needed. */\nval CucutoSeed = ${kHex(SEED)}\n\n`;
kt += `/** Material 3 tonal palettes generated from [CucutoSeed]. */\nobject CucutoPalette {\n`;
for (const [p, tones] of Object.entries(palettes)) {
  for (const [t, hex] of Object.entries(tones)) kt += `    val ${pascal(p)}${t} = ${kHex(hex)}\n`;
  kt += '\n';
}
kt = `${kt.trimEnd()}\n}\n\n`;
for (const [name, r] of Object.entries(schemes)) {
  const builder = name.startsWith('dark') ? 'darkColorScheme' : 'lightColorScheme';
  kt += `/** ${name} fallback scheme (dynamic color off). */\nval ${pascal(name)}ColorScheme: ColorScheme = ${builder}(\n`;
  kt += ROLES.map((role) => `    ${role} = ${kHex(r[role])},`).join('\n');
  kt += '\n)\n\n';
}
kt += `/** Example character accent seeds; the app derives these from each sprite at import. */\nobject CharacterAccentSeeds {\n`;
for (const [name, v] of Object.entries(characters)) kt += `    val ${pascal(name)} = ${kHex(v.seed)}\n`;
kt += '}\n';
writeFileSync(`${outDir}Color.kt`, kt);

// colors.css: custom properties for the SvelteKit site (light default, dark via media query or data-theme).
const cssBlock = (r) => ROLES.map((role) => `  --md-sys-color-${kebab(role)}: ${r[role]};`).join('\n');
let css = `/* ${generatedNote} */\n/* Usage: light by default; dark follows the OS unless <html data-theme="light|dark"> overrides it. */\n\n`;
css += `:root {\n  --cucuto-seed: ${SEED};\n`;
for (const [p, tones] of Object.entries(palettes)) {
  for (const [t, hex] of Object.entries(tones)) css += `  --md-ref-palette-${kebab(p)}${t}: ${hex};\n`;
}
css += `}\n\n:root,\n:root[data-theme='light'] {\n  color-scheme: light;\n${cssBlock(schemes.light)}\n}\n\n`;
css += `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme='light']) {\n    color-scheme: dark;\n${cssBlock(schemes.dark).replace(/^ {2}/gm, '    ')}\n  }\n}\n\n`;
css += `:root[data-theme='dark'] {\n  color-scheme: dark;\n${cssBlock(schemes.dark)}\n}\n\n`;
css += `@media (prefers-contrast: more) {\n  :root:not([data-theme='dark']) {\n${cssBlock(schemes.lightHighContrast).replace(/^ {2}/gm, '    ')}\n  }\n}\n\n`;
css += `@media (prefers-contrast: more) and (prefers-color-scheme: dark) {\n  :root:not([data-theme='light']) {\n${cssBlock(schemes.darkHighContrast).replace(/^ {2}/gm, '    ')}\n  }\n}\n\n`;
css += `/* Character accents: put data-character="leaf" on a card to recolor its primary roles. */\n`;
for (const [name, v] of Object.entries(characters)) {
  const block = (c) => Object.entries(c).map(([r, hex]) => `--md-sys-color-${kebab(r)}: ${hex};`).join(' ');
  css += `[data-character='${name}'] { ${block(v.light)} }\n`;
  css += `@media (prefers-color-scheme: dark) { :root:not([data-theme='light']) [data-character='${name}'] { ${block(v.dark)} } }\n`;
  css += `:root[data-theme='dark'] [data-character='${name}'] { ${block(v.dark)} }\n`;
}
writeFileSync(`${outDir}colors.css`, css);

console.log(JSON.stringify({ seed: SEED, light: schemes.light, dark: schemes.dark, primary: palettes.primary, tertiary: palettes.tertiary, neutral: palettes.neutral, characters }, null, 1));
